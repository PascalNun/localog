/**
 * Every word the application says, in Simplified Chinese.
 *
 * Typed against English, so this file cannot be missing a key or inventing one.
 *
 * ## Decisions taken once, here, so the whole application reads as one voice
 *
 * **会议纪要, never a transliteration of "protocol".** 协议 is an agreement or a
 * communications protocol and names the wrong object entirely. 会议纪要 is the
 * document a Chinese design or engineering office actually circulates after a
 * meeting, with the expected shape — participants, decisions, action items with
 * owners. 会议记录 is the fuller verbatim record and is what this product's
 * *transcript* is nearer to, which is a second reason not to use it for the
 * finished document.
 *
 * **转写 for transcription, 转写稿 for the transcript.** 转写 is what Chinese
 * speech products use for turning audio into text. 听写 is dictation and 转录
 * carries a biological sense.
 *
 * **您, not 你.** Written for offices keeping the formal record of meetings,
 * matching the German *Sie*, the French *vous* and the Korean 합니다체. Chinese
 * software often uses 你; 您 is the register this product is in.
 *
 * **会议 for a meeting, 录音 for a recording, 音轨 for a track, 说话人 for a
 * speaker** — the last being the term Chinese diarisation work uses.
 *
 * **Simplified only, and `zh` matches every Chinese tag.** A reader whose system
 * is set to zh-TW or zh-HK is served Simplified rather than nothing, which is the
 * better of two imperfect answers until somebody writes Traditional. Chinese has
 * no plural, so the count functions collapse to one form with a measure word.
 */

